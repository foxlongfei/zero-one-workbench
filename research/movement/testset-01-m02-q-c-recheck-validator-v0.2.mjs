const checks=[];const check=(name,pass,detail)=>checks.push({name,pass:Boolean(pass),detail});
check('task id preserved',a.task_id==='M02',a.task_id);
check('C reviewer',a.reviewer_role==='C',a.reviewer_role);
check('schema-only repair',a.inputs.repair_type==='SCHEMA_ONLY'&&!a.recheck.observation_or_count_changed,a.recheck);
check('hashes 8/8',a.recheck.frozen_hashes_match==='8/8',a.recheck.frozen_hashes_match);
check('recordings 6/6',a.recheck.recording_coverage==='6/6',a.recheck.recording_coverage);
check('taxonomy 6/6',a.recheck.taxonomy_coverage==='6/6',a.recheck.taxonomy_coverage);
