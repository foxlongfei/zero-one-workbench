check('M03/M04 remain blocked',a.dependency_state.M03==='BLOCKED_CLEAN_CONTEXT'&&a.dependency_state.M04==='BLOCKED_BY_M03',a.dependency_state);
check('D independence protected',a.dependency_state.D_independence==='PROTECTED',a.dependency_state);
const passed=checks.filter(x=>x.pass).length;
console.log(JSON.stringify({validator:'TESTSET-01-M02-Q-C-RECHECK-VALIDATOR-V0.2',passed,total:checks.length,checks},null,2));
if(passed!==checks.length)process.exit(1);
