check('L1 candidate-only boundary',a.recheck.evidence_level==='L1'&&a.recheck.candidate_only,a.recheck);
check('all reps UNKNOWN',a.recheck.all_rep_classifications==='UNKNOWN',a.recheck.all_rep_classifications);
check('no 30vs60/depth/quality overclaim',[a.recheck.thirty_vs_sixty,a.recheck.true_depth,a.recheck.movement_quality].every(x=>x==='NOT_ESTABLISHED'),a.recheck);
check('M02 accepted at procedural scope',a.decision.m02_acceptance&&a.decision.status==='M02_ACCEPTED_L1_CANDIDATE_ONLY',a.decision);
